SELECT DISTINCT COD_NDG_DEBI FROM DWHT_FATTI A -- DISTINCT ELIMINA I DOPPIONI 
WHERE COD_SOCRIFERIMENTO = '15' 
AND ( (NUM_ANNO = (SELECT SUBSTR(CHAR(DAT_CONT,ISO),1,4) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15') --ANNO 2023
       AND NUM_MESE <= (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT --> 2023 <= 12
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) -- MESI 12 
   OR (NUM_ANNO = (SELECT (SUBSTR(CHAR(DAT_CONT - 1 YEAR,ISO),1,4)) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' AND NOT MONTH(DAT_CONT) = 12) --2022
	   AND NUM_MESE > (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT -- 2022 > 12
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) )
AND ( (IMP_MCRE_NAPT_NOTF + IMP_MCRE_NAPT_NNOT) > 0 OR (IMP_MCRE_APTO_NOTF + IMP_MCRE_APTO_NNOT) > 0)
