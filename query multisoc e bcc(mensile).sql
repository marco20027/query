SET CURRENT SQLID ='CCFP01'

SELECT ORDINALE, CASE ORDINALE 
WHEN 'A' THEN 'Numero dei cedenti attivi per TO' 
WHEN 'B' THEN 'Numerosita dei cedenti' 
WHEN 'C' THEN 'Numerosita dei ceduti'
END AS DES_RIGA, COUNT(*) AS NROREC
FROM 
(SELECT DISTINCT 'A' AS ORDINALE, COD_NDG_CEDE AS SOGG FROM DWHT_FATTI A
WHERE A.COD_SOCRIFERIMENTO = '15' 
AND ( (A.NUM_ANNO = (SELECT SUBSTR(CHAR(DAT_CONT,ISO),1,4) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15') 
       AND A.NUM_MESE <= (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) 
   OR (A.NUM_ANNO = (SELECT (SUBSTR(CHAR(DAT_CONT - 1 YEAR,ISO),1,4)) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' AND NOT MONTH(DAT_CONT) = 12) 
	   AND A.NUM_MESE > (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) )
AND (A.IMP_TURN_PEND_PROG > 0 OR A.IMP_TURN_PUTO_PROG > 0) 
UNION
SELECT DISTINCT 'B' AS ORDINALE, COD_NDG_CEDE AS SOGG FROM DWHT_FATTI A
WHERE A.COD_SOCRIFERIMENTO = '15' 
AND ( (A.NUM_ANNO = (SELECT SUBSTR(CHAR(DAT_CONT,ISO),1,4) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15') 
       AND A.NUM_MESE <= (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) 
   OR (A.NUM_ANNO = (SELECT (SUBSTR(CHAR(DAT_CONT - 1 YEAR,ISO),1,4)) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' AND NOT MONTH(DAT_CONT) = 12) 
	   AND A.NUM_MESE > (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) )
AND ( ((A.IMP_MCRE_NAPT_NOTF + A.IMP_MCRE_NAPT_NNOT) > 0 OR (A.IMP_MCRE_APTO_NOTF + A.IMP_MCRE_APTO_NNOT) > 0)
  OR   (A.IMP_TURN_PEND_PROG > 0 OR A.IMP_TURN_PUTO_PROG > 0) ) 
UNION
SELECT DISTINCT 'C' AS ORDINALE, COD_NDG_DEBI AS SOGG FROM DWHT_FATTI A
WHERE A.COD_SOCRIFERIMENTO = '15' 
AND ( (A.NUM_ANNO = (SELECT SUBSTR(CHAR(DAT_CONT,ISO),1,4) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15') 
       AND A.NUM_MESE <= (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) 
   OR (A.NUM_ANNO = (SELECT (SUBSTR(CHAR(DAT_CONT - 1 YEAR,ISO),1,4)) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' AND NOT MONTH(DAT_CONT) = 12) 
	   AND A.NUM_MESE > (SELECT SUBSTR(CHAR(DAT_CONT,ISO),6,2) FROM TCON_DATCONT 
                     WHERE FLAG_TIPO_ELAB = 'M' AND COD_SOCRIFERIMENTO = '15' ) ) )
AND ( (A.IMP_MCRE_NAPT_NOTF + A.IMP_MCRE_NAPT_NNOT) > 0 OR (A.IMP_MCRE_APTO_NOTF + A.IMP_MCRE_APTO_NNOT) > 0)
) AS A
GROUP BY ORDINALE
WITH UR

